let currentResult = null;

// Initialize date selectors
document.addEventListener('DOMContentLoaded', () => {
  const yearSelect = document.getElementById('birth-year');
  const monthSelect = document.getElementById('birth-month');
  const daySelect = document.getElementById('birth-day');

  const currentYear = new Date().getFullYear();
  for (let y = currentYear; y >= 1930; y--) {
    const opt = document.createElement('option');
    opt.value = y;
    opt.textContent = `${y}年`;
    yearSelect.appendChild(opt);
  }

  for (let m = 1; m <= 12; m++) {
    const opt = document.createElement('option');
    opt.value = m;
    opt.textContent = `${m}月`;
    monthSelect.appendChild(opt);
  }

  for (let d = 1; d <= 31; d++) {
    const opt = document.createElement('option');
    opt.value = d;
    opt.textContent = `${d}日`;
    daySelect.appendChild(opt);
  }
});

function showPhase(phaseId) {
  document.querySelectorAll('[id^="phase-"]').forEach(el => el.classList.add('hidden'));
  document.getElementById(phaseId).classList.remove('hidden');
}

function startNumerology() {
  const year = parseInt(document.getElementById('birth-year').value);
  const month = parseInt(document.getElementById('birth-month').value);
  const day = parseInt(document.getElementById('birth-day').value);

  if (!year || !month || !day) {
    alert('生年月日を入力してください');
    return;
  }

  showPhase('phase-loading');

  setTimeout(() => {
    const lifePathNumber = calcLifePathNumber(year, month, day);
    const calcString = getCalcString(year, month, day);
    const personalYear = calcPersonalYear(month, day);
    const reading = READINGS[lifePathNumber];
    const personalYearText = PERSONAL_YEAR_TEXTS[personalYear] || PERSONAL_YEAR_TEXTS[personalYear % 9 || 9];

    currentResult = {
      year, month, day,
      lifePathNumber,
      calcString,
      personalYear,
      reading,
      personalYearText
    };

    displayResult(currentResult);
    showPhase('phase-result');
    window.scrollTo({ top: 0, behavior: 'smooth' });
  }, 2000);
}

function displayResult(result) {
  document.getElementById('result-number').textContent = result.lifePathNumber;
  document.getElementById('result-title').textContent = result.reading.title;
  document.getElementById('result-calc').textContent = result.calcString;
  document.getElementById('result-personality').textContent = result.reading.personality;
  document.getElementById('result-theme').textContent = result.reading.lifeTheme;
  document.getElementById('result-career').textContent = result.reading.career;
  document.getElementById('result-love').textContent = result.reading.love;

  const currentYear = new Date().getFullYear();
  document.getElementById('result-py-number').textContent = `${currentYear}年のパーソナルイヤー数：${result.personalYear}`;
  document.getElementById('result-personal-year').textContent = result.personalYearText;
}

function resetNumerology() {
  currentResult = null;
  showPhase('phase-input');
  window.scrollTo({ top: 0, behavior: 'smooth' });
}

