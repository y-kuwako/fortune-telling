// --- Life Path Number Calculation ---

function reduceToSingle(num) {
  // Keep master numbers 11, 22, 33
  if (num === 11 || num === 22 || num === 33) return num;
  while (num > 9) {
    let sum = 0;
    while (num > 0) {
      sum += num % 10;
      num = Math.floor(num / 10);
    }
    num = sum;
    if (num === 11 || num === 22 || num === 33) return num;
  }
  return num;
}

function calcLifePathNumber(year, month, day) {
  // Sum all digits of the full date
  const dateStr = `${year}${String(month).padStart(2, '0')}${String(day).padStart(2, '0')}`;
  let total = 0;
  for (const ch of dateStr) {
    total += parseInt(ch);
  }
  return reduceToSingle(total);
}

function getCalcString(year, month, day) {
  const dateStr = `${year}${String(month).padStart(2, '0')}${String(day).padStart(2, '0')}`;
  const digits = dateStr.split('');
  let total = digits.reduce((sum, d) => sum + parseInt(d), 0);
  let steps = [`${year}年${month}月${day}日 → ${digits.join('+')} = ${total}`];

  while (total > 9 && total !== 11 && total !== 22 && total !== 33) {
    const digs = String(total).split('');
    const newTotal = digs.reduce((sum, d) => sum + parseInt(d), 0);
    steps.push(`${digs.join('+')} = ${newTotal}`);
    total = newTotal;
  }

  return steps.join(' → ');
}

function calcPersonalYear(birthMonth, birthDay) {
  const currentYear = new Date().getFullYear();
  const dateStr = `${currentYear}${String(birthMonth).padStart(2, '0')}${String(birthDay).padStart(2, '0')}`;
  let total = 0;
  for (const ch of dateStr) {
    total += parseInt(ch);
  }
  return reduceToSingle(total);
}

